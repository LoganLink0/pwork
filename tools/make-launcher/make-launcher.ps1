# make-launcher · 从 launcher.json 生成 Windows 双击启动器（IExpress 自解压 exe）
# 用法与坑见同目录 README.md。生成物：ProjectDir\tools\launch.cmd + start-servers.cmd + launcher.sed + <name>-Launcher.exe
param(
  [Parameter(Mandatory = $true)][string]$ConfigPath
)

$ErrorActionPreference = 'Stop'
$cfg = Get-Content $ConfigPath -Raw -Encoding UTF8 | ConvertFrom-Json
$projectDir = (Resolve-Path $cfg.projectDir).Path
if (-not (Test-Path (Join-Path $projectDir 'package.json'))) { throw "projectDir 下没有 package.json：$projectDir" }
if (-not $cfg.services -or $cfg.services.Count -eq 0) { throw 'services 不能为空' }
$primary = $cfg.services[0]
$name = $cfg.name
$tools = Join-Path $projectDir 'tools'
New-Item -ItemType Directory -Force -Path $tools | Out-Null
$fallbackLine = ''
if ($cfg.appDirFallback) {
  $fallbackLine = "if not defined APPDIR if exist `"$($cfg.appDirFallback)\package.json`" set `"APPDIR=$($cfg.appDirFallback)`"`r`n"
}

$crlf = [System.Text.Encoding]::UTF8
function Write-CmdFile([string]$path, [string[]]$lines) {
  [System.IO.File]::WriteAllText($path, ($lines -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))
}

# ---------- tools\start-servers.cmd：真正拉服务，逐端口幂等 ----------
$ss = @(
  '@echo off',
  'setlocal',
  'rem ==== generated by make-launcher：逐端口幂等，端口空闲才启动，重复运行不冲突 ====',
  'cd /d "%~dp0.."',
  'if not exist node_modules (',
  '  echo First run: installing dependencies...',
  '  npm install',
  ')'
)
foreach ($s in $cfg.services) {
  $ss += "netstat -ano | findstr /C:`":$($s.port) `" | findstr /C:`"LISTENING`" >nul 2>&1"
  $ss += "if errorlevel 1 start `"$($s.name)`" /min cmd /c `"$($s.start) >> $($s.log) 2>&1`""
}
$ss += 'exit /b 0'
Write-CmdFile (Join-Path $tools 'start-servers.cmd') $ss

# ---------- tools\launch.cmd：探测目录 → explorer 转发 → 轮询主端口 → 打开页面 ----------
$lc = @(
  '@echo off',
  'setlocal',
  'rem ==== generated by make-launcher (see make-launcher kit README for pitfalls) ====',
  'rem IMPORTANT: services start via explorer relay, or IExpress job-close kills them',
  "set `"PORT=$($primary.port)`"",
  'set "APPDIR="',
  'if exist "%~dp0..\package.json" set "APPDIR=%~dp0.."',
  'if not defined APPDIR if exist "%~dp0package.json" set "APPDIR=%~dp0"',
  'if not defined APPDIR if exist "%CD%\package.json" set "APPDIR=%CD%"'
)
if ($cfg.appDirFallback) { $lc += "if not defined APPDIR if exist `"$($cfg.appDirFallback)\package.json`" set `"APPDIR=$($cfg.appDirFallback)`"" }
$lc += @(
  'if not defined APPDIR (',
  '  echo Project dir not found. Run tools\launch.cmd directly, or edit the fallback lines above.',
  '  pause',
  '  exit /b 1',
  ')',
  'rem ---- skip ports already listening; relay-start the rest ----',
  'set "NEEDSTART="'
)
foreach ($s in $cfg.services) {
  $lc += "netstat -ano | findstr /C:`":$($s.port) `" | findstr /C:`"LISTENING`" >nul 2>&1"
  $lc += 'if errorlevel 1 set "NEEDSTART=1"'
}
$lc += @(
  'if not defined NEEDSTART goto wait',
  'rem relay via the PROJECT copy of start-servers.cmd (explorer is outside the IExpress job)',
  'explorer "%APPDIR%\tools\start-servers.cmd"',
  ":wait",
  "ping -n 3 127.0.0.1 >nul",
  "curl -s -o nul http://127.0.0.1:$($primary.port)$($primary.healthPath)",
  'if not errorlevel 1 goto ready',
  'set /a TRIES+=1',
  'if %TRIES% lss 40 goto wait',
  "echo Service failed to start on port $($primary.port). Log: %APPDIR%\\$($primary.log)",
  'pause',
  'exit /b 1',
  ":ready"
)
foreach ($s in ($cfg.services | Select-Object -Skip 1)) {
  $lc += @(
    "set /a TRIES=0",
    ":wait_$($s.name)",
    'ping -n 3 127.0.0.1 >nul',
    "curl -s -o nul http://127.0.0.1:$($s.port)$($s.healthPath)",
    'if not errorlevel 1 goto ready_' + "$($s.name)",
    'set /a TRIES+=1',
    "if %TRIES% lss 10 goto wait_$($s.name)",
    "echo $($s.name) not ready on $($s.port) - non-fatal. Log: %APPDIR%\\$($s.log)"
  )
}
$lc += @(
  'explorer "' + $cfg.openUrl + '"',
  'exit /b 0'
)
Write-CmdFile (Join-Path $tools 'launch.cmd') $lc

# ---------- tools\launcher.sed ----------
$sed = @(
  '[Version]',
  'Class=IEXPRESS',
  'SEDVersion=3',
  '[Options]',
  'PackagePurpose=InstallApp',
  'ShowInstallProgramWindow=0',
  'HideInstallProgram=1',
  'AppLaunched=%AppLaunched%',
  'PostInstallCmd=%PostInstallCmd%',
  'AdminQuietInstCmd=%AdminQuietInstCmd%',
  'UserQuietInstCmd=%UserQuietInstCmd%',
  'SourceFiles=SourceFiles',
  'HideExtractAnimation=0',
  'UseLongFileName=1',
  'InsideCompressed=0',
  'CAB_FixedSize=0',
  'CAB_ResvCodeSigning=0',
  'RebootMode=I',
  'InstallPrompt=%InstallPrompt%',
  'DisplayLicense=%DisplayLicense%',
  'FinishMessage=%FinishMessage%',
  'TargetName=%TargetName%',
  'FriendlyName=%FriendlyName%',
  '[Strings]',
  'InstallPrompt=',
  'DisplayLicense=',
  'FinishMessage=',
  "FriendlyName=$name Launcher",
  'AppLaunched=launch.cmd',
  'PostInstallCmd=<None>',
  'AppRemovalCmd=',
  'AdminQuietInstCmd=',
  'UserQuietInstCmd=',
  "Title=$name Launcher",
  "MediaLabel1=$name Launcher",
  "TargetName=$(Join-Path $projectDir "$name-Launcher.exe")",
  "SourceFiles0=$tools\",
  'FILE0="launch.cmd"',
  'FILE1="start-servers.cmd"',
  '[SourceFiles]',
  "SourceFiles0=$tools\",
  '[SourceFiles0]',
  '%FILE0%=',
  '%FILE1%='
)
[System.IO.File]::WriteAllText((Join-Path $tools 'launcher.sed'), ($sed -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))

# ---------- 打包（直接调 iexpress；PowerShell 无 Git Bash 的路径转换问题） ----------
$target = Join-Path $projectDir "$name-Launcher.exe"
if (Test-Path $target) { Remove-Item $target -Force }
$sedPath = Join-Path $tools 'launcher.sed'
& "$env:SystemRoot\System32\iexpress.exe" /N /Q /M $sedPath | Out-Null
Start-Sleep -Seconds 2
if (-not (Test-Path $target)) {
  throw "打包失败：$target 未生成。若屏幕弹出 IExpress 向导，多半是 SED 缺 [Strings] 键——用本工具重新生成即可"
}
Write-Host "OK  $target（$([math]::Round((Get-Item $target).Length / 1KB)) KB）"
Write-Host "双击 exe：按端口幂等拉起服务 → 打开 $($cfg.openUrl)；子命令日志在项目根 launcher-*.log"
